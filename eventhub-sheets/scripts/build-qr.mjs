// Bundles the MIT-licensed QR encoder by Kazuhiko Arase (as vendored in the
// qrcode-terminal package) into apps-script/Qr.gs, so certificates can carry a QR
// code without any external service. Run: node scripts/build-qr.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, '..', '..', 'node_modules', 'qrcode-terminal', 'vendor', 'QRCode');
const mods = fs.readdirSync(src).filter((f) => f.endsWith('.js'));
let out = `/**
 * QR code encoder for certificates. Generated by scripts/build-qr.mjs; do not edit.
 *
 * QRCode for JavaScript, Copyright (c) 2009 Kazuhiko Arase, http://www.d-project.com/
 * Licensed under the MIT license: http://www.opensource.org/licenses/mit-license.php
 * The word "QR Code" is a registered trademark of DENSO WAVE INCORPORATED.
 *
 * qrMatrix_(text) -> array of rows of booleans (true = dark module), ECC level M.
 */
var QR_LIB_ = (function () {
  var defs = {};
  var cache = {};
  function req(name) {
    var key = name.split('/').pop().split('.js')[0];
    if (cache[key]) return cache[key].exports;
    var module = { exports: {} };
    cache[key] = module;
    defs[key](module, module.exports, req);
    return module.exports;
  }
`;
for (const f of mods) {
  const code = fs.readFileSync(path.join(src, f), 'utf8');
  out += `  defs[${JSON.stringify(f.replace(/\.js$/, ''))}] = function (module, exports, require) {\n${code}\n  };\n`;
}
out += `  return { QRCode: req('index'), Level: req('QRErrorCorrectLevel') };
})();

function qrMatrix_(text) {
  var qr = new QR_LIB_.QRCode(-1, QR_LIB_.Level.M);
  qr.addData(String(text));
  qr.make();
  var n = qr.getModuleCount();
  var rows = [];
  for (var r = 0; r < n; r++) {
    var line = [];
    for (var c = 0; c < n; c++) line.push(qr.isDark(r, c));
    rows.push(line);
  }
  return rows;
}
`;
fs.writeFileSync(path.join(here, '..', 'apps-script', 'Qr.gs'), out);
console.log(`Wrote apps-script/Qr.gs from ${mods.length} modules`);
